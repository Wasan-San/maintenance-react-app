-- Workscape Maintenance — Week 3 Supabase setup
-- Run this once in Supabase SQL Editor BEFORE running the migrated React app.
-- This script upgrades the Week 2 learning schema so the existing Maintenance UI
-- can use Supabase as its main data source.

-- 1) Business date: request_date is a date, while created_at/last_update keep timestamps.
alter table public.tickets alter column request_date drop default;
alter table public.tickets alter column request_date type date using request_date::date;
alter table public.tickets alter column request_date set default current_date;

-- 2) Add the fields already used by the React UI.
alter table public.tickets add column if not exists issue_title text;
alter table public.tickets add column if not exists reporter_email text;
alter table public.tickets add column if not exists reporter_mobile text;
alter table public.tickets add column if not exists hq_support text;
alter table public.tickets add column if not exists charge_type text;
alter table public.tickets add column if not exists cost_category text;
alter table public.tickets add column if not exists actual_cost numeric(12,2) not null default 0;
alter table public.tickets add column if not exists admin_notes text;
alter table public.tickets add column if not exists last_update timestamptz not null default now();
alter table public.tickets add column if not exists history jsonb not null default '[]'::jsonb;

-- 3) Vendor master (shared master data; can later be reused by Project module).
create table if not exists public.vendors (
  vendor_id bigint generated by default as identity primary key,
  vendor_name text unique not null,
  contact_email text,
  contact_phone text,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

insert into public.vendors (vendor_name)
values
  ('ABC Service Co., Ltd.'),
  ('Bright Works Co., Ltd.'),
  ('Cool Air Service'),
  ('FixPro Thailand'),
  ('Metro Facility Service')
on conflict (vendor_name) do nothing;

-- Add FK only if it does not already exist.
do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'tickets_vendor_id_fkey'
      and conrelid = 'public.tickets'::regclass
  ) then
    alter table public.tickets
      add constraint tickets_vendor_id_fkey
      foreign key (vendor_id)
      references public.vendors(vendor_id)
      on delete set null;
  end if;
end $$;

-- 4) Normalize the Week 2 sample data so it matches the React workflow vocabulary.
update public.tickets set category = 'AC System' where category = 'AC';
update public.tickets set category = 'Lighting & Logo' where category = 'Lighting';
update public.tickets set status = 'New Request' where status = 'Pending';
update public.tickets set status = 'On-Site Work' where status = 'In Progress';

-- Keep the readable Work Code format used by the React UI.
update public.tickets
set ticket_code = 'MT-2026-' || lpad(ticket_id::text, 3, '0')
where ticket_code like 'MT_26_%';

-- 5) Backfill new columns from data that already exists.
update public.tickets
set issue_title = coalesce(issue_title, description),
    cost_category = coalesce(cost_category, category),
    last_update = coalesce(last_update, created_at, now())
where true;

update public.tickets t
set reporter_email = coalesce(t.reporter_email, s.store_email)
from public.stores s
where t.store_id = s.store_id
  and t.reporter_email is null;

update public.tickets
set history = jsonb_build_array(
  jsonb_build_object(
    'status', 'New Request',
    'date', coalesce(created_at, now()),
    'by', 'Store Staff'
  )
)
where history = '[]'::jsonb;

-- 6) Week 3 training permissions.
-- RLS comes back in Week 4 with Auth + real policies.
alter table public.stores disable row level security;
alter table public.tickets disable row level security;
alter table public.vendors disable row level security;

grant usage on schema public to anon, authenticated;
grant select on table public.stores to anon, authenticated;
grant select, insert, update, delete on table public.tickets to anon, authenticated;
grant select on table public.vendors to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

-- 7) Quick verification.
select 'stores' as table_name, count(*) as rows from public.stores
union all
select 'tickets', count(*) from public.tickets
union all
select 'vendors', count(*) from public.vendors;
