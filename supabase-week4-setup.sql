-- Workscape Maintenance — Week 4 setup
-- Auth + Profiles + Role permissions (RLS) + Storage/Photos
-- Run AFTER supabase-week3-setup.sql.

begin;

-- ------------------------------------------------------------
-- 1) Profiles: business role linked to Supabase Auth user
-- ------------------------------------------------------------
create table if not exists public.profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  role text not null check (role in ('store', 'viewer', 'admin')),
  store_id bigint references public.stores(store_id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint store_role_requires_store check (
    role <> 'store' or store_id is not null
  )
);

-- Helper functions let RLS ask "who is this user?" without recursive profile policies.
create or replace function public.current_user_role()
returns text
language sql
stable
security definer
set search_path = public
as $$
  select role from public.profiles where user_id = auth.uid();
$$;

create or replace function public.current_user_store_id()
returns bigint
language sql
stable
security definer
set search_path = public
as $$
  select store_id from public.profiles where user_id = auth.uid();
$$;

revoke all on function public.current_user_role() from public;
revoke all on function public.current_user_store_id() from public;
grant execute on function public.current_user_role() to authenticated;
grant execute on function public.current_user_store_id() to authenticated;

-- ------------------------------------------------------------
-- 2) Database-generated Work Code
--    Client no longer needs to calculate the next number.
-- ------------------------------------------------------------
create sequence if not exists public.maintenance_ticket_code_seq;

select setval(
  'public.maintenance_ticket_code_seq',
  greatest(
    coalesce((
      select max((substring(ticket_code from '([0-9]+)$'))::bigint)
      from public.tickets
      where ticket_code ~ '[0-9]+$'
    ), 0),
    1
  ),
  true
);

create or replace function public.set_ticket_code()
returns trigger
language plpgsql
as $$
begin
  if new.ticket_code is null or btrim(new.ticket_code) = '' then
    new.ticket_code :=
      'MT-' || to_char(coalesce(new.request_date, current_date), 'YYYY') || '-' ||
      lpad(nextval('public.maintenance_ticket_code_seq')::text, 3, '0');
  end if;
  return new;
end;
$$;

drop trigger if exists tickets_set_ticket_code on public.tickets;
create trigger tickets_set_ticket_code
before insert on public.tickets
for each row execute function public.set_ticket_code();

grant usage, select on sequence public.maintenance_ticket_code_seq to authenticated;

-- ------------------------------------------------------------
-- 3) Photo metadata table
--    Binary file -> Storage; metadata/reference -> PostgreSQL
-- ------------------------------------------------------------
create table if not exists public.ticket_photos (
  photo_id bigint generated by default as identity primary key,
  ticket_id bigint not null references public.tickets(ticket_id) on delete cascade,
  storage_path text unique not null,
  photo_type text not null check (photo_type in ('reported', 'admin')),
  stage text,
  uploaded_by uuid default auth.uid() references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create index if not exists ticket_photos_ticket_id_idx
  on public.ticket_photos(ticket_id);

-- ------------------------------------------------------------
-- 4) Storage bucket (private)
-- ------------------------------------------------------------
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'maintenance-photos',
  'maintenance-photos',
  false,
  5242880,
  array['image/jpeg','image/png','image/webp','image/heic','image/heif']
)
on conflict (id) do update
set public = excluded.public,
    file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;

-- ------------------------------------------------------------
-- 5) Turn RLS back ON
-- ------------------------------------------------------------
alter table public.profiles enable row level security;
alter table public.stores enable row level security;
alter table public.tickets enable row level security;
alter table public.vendors enable row level security;
alter table public.ticket_photos enable row level security;

-- Remove Week 3 anonymous access.
revoke all on table public.stores from anon;
revoke all on table public.tickets from anon;
revoke all on table public.vendors from anon;
revoke all on table public.profiles from anon;
revoke all on table public.ticket_photos from anon;

-- Authenticated users get table privileges; RLS decides which rows/actions are allowed.
grant usage on schema public to authenticated;
grant select on public.profiles to authenticated;
grant select on public.stores to authenticated;
grant select, insert, update, delete on public.tickets to authenticated;
grant select on public.vendors to authenticated;
grant select, insert, delete on public.ticket_photos to authenticated;
grant usage, select on all sequences in schema public to authenticated;

-- ------------------------------------------------------------
-- 6) Profiles policies
-- ------------------------------------------------------------
drop policy if exists "profiles_read_own" on public.profiles;
create policy "profiles_read_own"
on public.profiles for select
to authenticated
using (user_id = auth.uid());

-- ------------------------------------------------------------
-- 7) Stores policies
-- store  = own store only
-- viewer/admin = all stores
-- ------------------------------------------------------------
drop policy if exists "stores_read_by_role" on public.stores;
create policy "stores_read_by_role"
on public.stores for select
to authenticated
using (
  public.current_user_role() in ('admin', 'viewer')
  or (
    public.current_user_role() = 'store'
    and store_id = public.current_user_store_id()
  )
);

-- ------------------------------------------------------------
-- 8) Vendors policies
-- Vendor names are readable by any signed-in user; writes stay unavailable.
-- ------------------------------------------------------------
drop policy if exists "vendors_read_team" on public.vendors;
create policy "vendors_read_team"
on public.vendors for select
to authenticated
using (auth.uid() is not null);

-- ------------------------------------------------------------
-- 9) Tickets policies
-- store  = READ own store + CREATE own store
-- viewer = READ all + CREATE
-- admin  = full CRUD
-- ------------------------------------------------------------
drop policy if exists "tickets_read_by_role" on public.tickets;
create policy "tickets_read_by_role"
on public.tickets for select
to authenticated
using (
  public.current_user_role() in ('admin', 'viewer')
  or (
    public.current_user_role() = 'store'
    and store_id = public.current_user_store_id()
  )
);

drop policy if exists "tickets_create_by_role" on public.tickets;
create policy "tickets_create_by_role"
on public.tickets for insert
to authenticated
with check (
  public.current_user_role() in ('admin', 'viewer')
  or (
    public.current_user_role() = 'store'
    and store_id = public.current_user_store_id()
  )
);

drop policy if exists "tickets_update_admin" on public.tickets;
create policy "tickets_update_admin"
on public.tickets for update
to authenticated
using (public.current_user_role() = 'admin')
with check (public.current_user_role() = 'admin');

drop policy if exists "tickets_delete_admin" on public.tickets;
create policy "tickets_delete_admin"
on public.tickets for delete
to authenticated
using (public.current_user_role() = 'admin');

-- ------------------------------------------------------------
-- 10) Photo metadata policies
-- SELECT follows ticket visibility.
-- Any authenticated role can add photos to a ticket it can see.
-- Delete is admin-only for this learning V1.
-- ------------------------------------------------------------
drop policy if exists "ticket_photos_read_visible_ticket" on public.ticket_photos;
create policy "ticket_photos_read_visible_ticket"
on public.ticket_photos for select
to authenticated
using (
  exists (
    select 1
    from public.tickets t
    where t.ticket_id = ticket_photos.ticket_id
  )
);

drop policy if exists "ticket_photos_insert_visible_ticket" on public.ticket_photos;
create policy "ticket_photos_insert_visible_ticket"
on public.ticket_photos for insert
to authenticated
with check (
  exists (
    select 1
    from public.tickets t
    where t.ticket_id = ticket_photos.ticket_id
  )
);

drop policy if exists "ticket_photos_delete_admin" on public.ticket_photos;
create policy "ticket_photos_delete_admin"
on public.ticket_photos for delete
to authenticated
using (public.current_user_role() = 'admin');

-- ------------------------------------------------------------
-- 11) Storage object policies
-- Path format: {store_id}/{ticket_id}/{photo_type}/filename
-- ------------------------------------------------------------
drop policy if exists "maintenance_photos_read" on storage.objects;
create policy "maintenance_photos_read"
on storage.objects for select
to authenticated
using (
  bucket_id = 'maintenance-photos'
  and (
    public.current_user_role() in ('admin', 'viewer')
    or (
      public.current_user_role() = 'store'
      and (storage.foldername(name))[1] = public.current_user_store_id()::text
    )
  )
);

drop policy if exists "maintenance_photos_upload" on storage.objects;
create policy "maintenance_photos_upload"
on storage.objects for insert
to authenticated
with check (
  bucket_id = 'maintenance-photos'
  and (
    public.current_user_role() in ('admin', 'viewer')
    or (
      public.current_user_role() = 'store'
      and (storage.foldername(name))[1] = public.current_user_store_id()::text
    )
  )
);

drop policy if exists "maintenance_photos_delete_admin" on storage.objects;
create policy "maintenance_photos_delete_admin"
on storage.objects for delete
to authenticated
using (
  bucket_id = 'maintenance-photos'
  and public.current_user_role() = 'admin'
);

commit;

-- ------------------------------------------------------------
